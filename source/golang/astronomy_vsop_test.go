package astronomy

import (
	"math"
	"strconv"
	"strings"
	"testing"
)

// timeFromIso parses a UTC timestamp in the form YYYY-MM-DDTHH:MM:SSZ (or with
// a fractional second) and returns the corresponding AstroTime.
func timeFromIso(text string, t *testing.T) AstroTime {
	fields := strings.Split(text, "T")
	date := strings.Split(fields[0], "-")
	timePart := strings.TrimSuffix(fields[1], "Z")
	clock := strings.Split(timePart, ":")
	atoi := func(s string) int {
		n, err := strconv.Atoi(s)
		if err != nil {
			t.Fatal(err)
		}
		return n
	}
	second := 0.0
	if len(clock) >= 3 {
		sec, err := strconv.ParseFloat(clock[2], 64)
		if err != nil {
			t.Fatal(err)
		}
		second = sec
	}
	return TimeFromCalendar(atoi(date[0]), atoi(date[1]), atoi(date[2]), atoi(clock[0]), atoi(clock[1]), second)
}

// vsopPosition computes the heliocentric equatorial position of a body using
// only the VSOP87 model and its rotation to equatorial coordinates.
// This exercises vsopFormulaCalc, vsopSphereToRect, and vsopRotate together.
func vsopPosition(body int, time AstroTime) AstroVector {
	t := time.Tt / daysPerMillennium
	sphere := vsopFormulaCalc(&vsop[body], t)
	eclip := vsopSphereToRect(sphere[vsopLonIndex], sphere[vsopLatIndex], sphere[vsopRadIndex])
	pos := vsopRotate(eclip)
	return AstroVector{X: pos.X, Y: pos.Y, Z: pos.Z, T: time}
}

func TestVsopHelioPosition(t *testing.T) {
	// Reference values generated by the Python implementation of Astronomy
	// Engine (HelioVector), which uses the identical VSOP87 data and math.
	cases := []struct {
		body int
		text string
		x    float64
		y    float64
		z    float64
	}{
		{int(Mercury), "2020-06-01T00:00:00Z", -3.9484287987022376e-01, -7.5977439681019290e-02, 3.4812337885479702e-04},
		{int(Venus), "2020-06-01T00:00:00Z", -2.6034626330234112e-01, -6.2361503520182837e-01, -2.6412311296607588e-01},
		{int(Mars), "2020-06-01T00:00:00Z", 6.2625480137296474e-01, -1.1409027506752543e+00, -5.4020647027386703e-01},
		{int(Jupiter), "2020-06-01T00:00:00Z", 1.6329503942165859e+00, -4.4960025833149668e+00, -1.9668008500675855e+00},
		{int(Mercury), "1800-01-01T00:00:00Z", -2.1101098936687412e-01, 2.1392933797923774e-01, 1.3621874296733821e-01},
		{int(Venus), "1800-01-01T00:00:00Z", -6.1468487647085657e-01, 3.2341481150171825e-01, 1.8427790057010721e-01},
		{int(Mars), "1800-01-01T00:00:00Z", -1.0962535386022048e+00, -1.0195362398580545e+00, -4.3740101120444824e-01},
		{int(Jupiter), "1800-01-01T00:00:00Z", -2.9515400879119705e-02, 4.7166029507595351e+00, 2.0232109507193012e+00},
		{int(Mercury), "2200-06-01T00:00:00Z", 7.2416888827955841e-02, -3.9603815367564432e-01, -2.1913528505286917e-01},
		{int(Venus), "2200-06-01T00:00:00Z", -8.3473318027326673e-02, 6.4945230260307540e-01, 2.9788596035428194e-01},
		{int(Mars), "2200-06-01T00:00:00Z", -1.6230390192993156e+00, -2.3497072142163450e-01, -6.4677950740047258e-02},
		{int(Jupiter), "2200-06-01T00:00:00Z", 4.9378853364979749e+00, -3.9648118782573238e-01, -2.8958817001468207e-01},
		{int(Mercury), "2023-03-15T21:50:00Z", 3.6019764170445095e-01, -4.7009693426852434e-02, -6.2441532578930078e-02},
		{int(Venus), "2023-03-15T21:50:00Z", 1.4395759415129175e-01, 6.4702969839876578e-01, 2.8203131556510730e-01},
		{int(Mars), "2023-03-15T21:50:00Z", -8.8166044412661992e-01, 1.2454876490013200e+00, 5.9506845655399687e-01},
		{int(Jupiter), "2023-03-15T21:50:00Z", 4.6819114958028605e+00, 1.5203922363221281e+00, 5.3770458364367679e-01},
	}
	for _, c := range cases {
		time := timeFromIso(c.text, t)
		pos := vsopPosition(c.body, time)
		dx := c.x - pos.X
		dy := c.y - pos.Y
		dz := c.z - pos.Z
		diff := math.Sqrt(dx*dx + dy*dy + dz*dz)
		// The Python reference and this Go code use identical data and math,
		// so the error should be at the double-precision rounding level.
		if diff > 1.0e-13 {
			t.Errorf("body=%s time=%s excessive position error = %g", BodyName(Body(c.body)), c.text, diff)
		}
	}
}
